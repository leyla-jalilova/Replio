OPENING_CUE = "Начни выбранный рабочий разговор первой репликой своего персонажа."


def start_conversation(scenario, user_role: str = MANAGER) -> str:
    """Генерирует первую реплику ИИ до сообщения пользователя."""
    if user_role == EMPLOYEE:
        cue = (
            "Начни разговор ПЕРВЫМ как руководитель. Сам назови конкретную рабочую "
            "ситуацию из сценария, объясни причину встречи и задай один уместный "
            "вопрос сотруднику. Не спрашивай неопределённо 'о чём поговорим?'. "
            "2–4 естественных предложения, без вступлений от имени ИИ."
        )
    else:
        cue = (
            "Начни разговор ПЕРВОЙ как сотрудник, который сам пришёл к руководителю. "
            "Сразу расскажи, что случилось именно в этом сценарии, почему это "
            "тебя беспокоит, и попроси руководителя помочь либо задай один "
            "конкретный вопрос. Не жди сообщения руководителя. "
            "Не спрашивай 'о чём вы хотите поговорить?'. "
            "Для конфликта: ты Марина, поссорилась с Денисом из-за распределения "
            "задач; объясни это от первого лица. Для демотивации не раскрывай "
            "сразу скрытую причину выгорания; начни с осторожной жалобы. "
            "Для увольнения ты ещё не знаешь о сокращении: начни с вопроса, "
            "зачем тебя пригласили, не утверждая, что знаешь причину. "
            "2–4 естественных предложения, без пояснений от имени ИИ."
        )
    messages = [
        {"role": "system", "content": build_system_prompt(scenario, user_role)},
        {"role": "user", "content": cue},
    ]
    answer = ask_ai(messages).strip()
    if not answer:
        raise ValueError("ИИ вернул пустую первую реплику")
    return answer


def build_history(scenario, user_role: str, stored_messages, new_message: str) -> list[dict]:
    # Собирает для ИИ: инструкцию + всю прошлую переписку + новое сообщение
    history = [{"role": "system", "content": build_system_prompt(scenario, user_role)}]
    # Некоторые модели требуют, чтобы диалог начинался с реплики пользователя
    if stored_messages and stored_messages[0].role == "assistant":
        history.append({"role": "user", "content": OPENING_CUE})
    history += [{"role": m.role, "content": m.content} for m in stored_messages]
    history.append({"role": "user", "content": new_message})
    return history


